import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const audit = JSON.parse(
  await readFile(resolve(root, 'data/inep/institution-source-audit.json'), 'utf8'),
);
const directory = JSON.parse(await readFile(resolve(root, 'data/inep/provenance.json'), 'utf8'));
if (audit.institutions.length !== 317) throw new Error('Expected 317 audited institutions');
const websites = audit.institutions
  .filter((item) => item.websiteReachable && item.status.endsWith('_site_live'))
  .map((item) => {
    const url = new URL(item.website);
    if (url.protocol !== 'https:' || url.username || url.password) {
      throw new Error(`Invalid website for Inep code ${item.id}`);
    }
    return [item.id, url.toString()];
  })
  .sort((a, b) => a[0] - b[0]);
if (new Set(websites.map(([id]) => id)).size !== websites.length) {
  throw new Error('Duplicate Inep code in audited websites');
}
const target = resolve(root, 'apps/web/src/app/features/official-catalog/audited-websites.ts');
const entries = websites.map(([id, url]) => `  ${id}: ${JSON.stringify(url)},`).join('\n');
await writeFile(
  target,
  `// Generated by scripts/generate-audited-websites.mjs from the source audit.\n` +
    `// Checked on ${audit.checkedOn}; institutional homepages, not selection portals.\n` +
    `export const AUDITED_INSTITUTIONAL_WEBSITES: Readonly<Record<number, string>> = {\n${entries}\n};\n`,
);
console.log(
  `Generated ${websites.length} audited institutional websites from Inep ${directory.referenceYear}.`,
);
