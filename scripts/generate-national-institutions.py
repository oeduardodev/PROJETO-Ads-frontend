"""Generate the catalog from the versioned projection of the official Inep CSV."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/inep/public-institutions-2024.csv'
TARGET = ROOT / 'apps/web/src/app/features/official-catalog/national-institutions.ts'
rows = list(csv.DictReader(SOURCE.open(encoding='utf-8')))
assert all(row['TP_REDE'] == '1' for row in rows)
assert len({row['CO_IES'] for row in rows}) == len(rows)
institutions = []
for row in rows:
    category = int(row['TP_CATEGORIA_ADMINISTRATIVA'])
    # Inep's national report includes special-category institutions in Municipal.
    jurisdiction = {1: 'FEDERAL', 2: 'ESTADUAL', 3: 'MUNICIPAL', 7: 'MUNICIPAL'}[category]
    institutions.append(dict(
        id=int(row['CO_IES']), name=row['NO_IES'], acronym=row['SG_IES'].strip() or f"IES {row['CO_IES']}",
        jurisdiction=jurisdiction, administrativeCategory=category,
        state=row['SG_UF_IES'], stateName=row['NO_UF_IES'], city=row['NO_MUNICIPIO_IES'],
        censusYear=int(row['NU_ANO_CENSO']),
    ))
institutions.sort(key=lambda item: (item['state'], item['name'], item['id']))
TARGET.write_text('// Generated by scripts/generate-national-institutions.py. Source: Inep Censo 2024.\n'
                  + 'export const NATIONAL_INSTITUTIONS = '
                  + json.dumps(institutions, ensure_ascii=False, indent=2) + ' as const;\n', encoding='utf-8')
print(f'Generated {len(institutions)} public institutions across {len({x["state"] for x in institutions})} UFs.')
